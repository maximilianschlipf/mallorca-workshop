CREATE TABLE IF NOT EXISTS trainer (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS abwesenheit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id VARCHAR(50) NOT NULL,
    von DATE NOT NULL,
    bis DATE NOT NULL,
    grund VARCHAR(255),
    CONSTRAINT fk_abwesenheit_trainer FOREIGN KEY (trainer_id) REFERENCES trainer(id)
);

CREATE TABLE IF NOT EXISTS schulung (
    id VARCHAR(50) PRIMARY KEY,
    titel VARCHAR(255) NOT NULL,
    kategorie VARCHAR(255) NOT NULL,
    kurzbeschreibung CLOB NOT NULL,
    dauer_in_tagen INT NOT NULL,
    mindestteilnehmer_exklusiv INT NOT NULL,
    max_teilnehmer_oeffentlich INT
);

CREATE TABLE IF NOT EXISTS voraussetzung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schulung_id VARCHAR(50) NOT NULL,
    text VARCHAR(500) NOT NULL,
    CONSTRAINT fk_voraussetzung_schulung FOREIGN KEY (schulung_id) REFERENCES schulung(id)
);

CREATE TABLE IF NOT EXISTS termin (
    termin_id VARCHAR(80) PRIMARY KEY,
    schulung_id VARCHAR(50) NOT NULL,
    startdatum DATE NOT NULL,
    enddatum DATE NOT NULL,
    ort VARCHAR(255) NOT NULL,
    format VARCHAR(50),
    status VARCHAR(50) NOT NULL,
    trainer_id VARCHAR(50),
    CONSTRAINT fk_termin_schulung FOREIGN KEY (schulung_id) REFERENCES schulung(id),
    CONSTRAINT fk_termin_trainer FOREIGN KEY (trainer_id) REFERENCES trainer(id)
);
