CREATE TABLE IF NOT EXISTS teilnehmerbuchung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termin_id VARCHAR(80) NOT NULL,
    name VARCHAR(255),
    firma VARCHAR(255) NOT NULL,
    bemerkung VARCHAR(1000),
    teilnahmestatus VARCHAR(30) NOT NULL DEFAULT 'offen',
    CONSTRAINT ck_teilnahmestatus CHECK
        (teilnahmestatus IN ('offen', 'teilgenommen', 'nicht_teilgenommen')),
