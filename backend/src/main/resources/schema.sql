CREATE TABLE IF NOT EXISTS benachrichtigung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empfaenger_id VARCHAR(36),
    empfaenger_rolle VARCHAR(30),
    anlasstyp VARCHAR(80) NOT NULL DEFAULT 'BESTAND',
    anlass VARCHAR(255) NOT NULL,
    bezug_art VARCHAR(30),
    bezug_id VARCHAR(80),
    erstellt_am TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gelesen BOOLEAN NOT NULL DEFAULT FALSE,
    gelesen_am TIMESTAMP,
    CONSTRAINT ck_benachrichtigung_empfaenger CHECK (
        (empfaenger_id IS NOT NULL AND empfaenger_rolle IS NULL)
        OR (empfaenger_id IS NULL AND empfaenger_rolle = 'ADMINISTRATOR')
    ),
    CONSTRAINT fk_benachrichtigung_konto FOREIGN KEY (empfaenger_id)
        REFERENCES benutzerkonto(id) ON DELETE CASCADE
);

