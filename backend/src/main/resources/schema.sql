    bis DATE,
    status VARCHAR(40) NOT NULL DEFAULT 'OFFEN',
    erstellt_am TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    entschieden_am TIMESTAMP,
